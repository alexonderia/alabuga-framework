import {readFile,writeFile,mkdir} from 'node:fs/promises';
const layers=JSON.parse(await readFile('design/token-layers.json','utf8'));
const snapshot=JSON.parse(await readFile('design/figma-tokens.json','utf8'));
const all=new Map();
for(const [layer,values] of Object.entries(layers))for(const [key,value]of Object.entries(values)){
 if(all.has(key))throw new Error('Duplicate token: '+key);all.set(key,value);
}
for(const [key,value]of all)for(const [,ref]of value.matchAll(/var\((--af-[\w-]+)/g))if(!all.has(ref))throw new Error(`${key}: unresolved ${ref}`);
if(!snapshot.variables?.length)throw new Error('Missing Figma token snapshot');
await mkdir('src/tokens',{recursive:true});
for(const [layer,values]of Object.entries(layers)){
 const file=`src/tokens/${layer}.css`,content=`/* Generated by npm run tokens. */\n:root {\n${Object.entries(values).map(([k,v])=>`  ${k}: ${v};`).join('\n')}\n}\n`;
 if(process.argv.includes('--check')){if(await readFile(file,'utf8')!==content)throw new Error('Stale tokens: '+file)}else await writeFile(file,content);
}
const entry=['core','semantic','components'].map(n=>`@import './tokens/${n}.css';`).join('\n')+'\n';
if(process.argv.includes('--check')){if(await readFile('src/tokens.css','utf8')!==entry)throw new Error('Stale token entry')}else await writeFile('src/tokens.css',entry);
console.log(`${all.size} tokens: references and generated layers verified`);
